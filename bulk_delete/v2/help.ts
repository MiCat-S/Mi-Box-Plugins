import {ui} from "telebox/sdk";

export function renderHelp(prefix: string): string {
  const p = ui.text(prefix);
  return `🧹 <b>批量删除消息</b>

支持按回复范围删除，或删除自己最近发送的消息。

<b>命令：</b>
• 回复一条消息后发送 <code>${p}bd</code> — 删除被回复消息到当前命令之间符合条件的消息，含边界
• <code>${p}bd 数量</code> — 删除自己最近的消息；数量为 1–99 的整数
• <code>${p}bd on</code> — 允许在拥有删除权限时选择他人的消息
• <code>${p}bd off</code> — 回复范围模式只选择自己的消息

<b>范围与权限：</b>
• 数量模式从当前对话最近 100 条消息中筛选自己的消息，按时间倒序取前 N 条删除；不足 N 条时删除实际找到的数量，命令消息也会删除。
• 回复范围模式每次最多获取 100 条消息。较长区间需要检查剩余消息，再选择范围继续处理。
• 删除他人消息的开关默认开启，按当前登录账号保存，在各对话间共用。
• on 只控制插件选择范围；群组中仍需要群主身份或管理员的删除消息权限。
• 回复消息时优先使用回复范围，数量模式请发送一条独立命令。
• 删除以撤回方式执行，成功删除的消息无法通过本插件恢复。

<b>示例：</b>
• <code>${p}bd 10</code> — 删除最近扫描范围内自己的 10 条消息
• 先发送 <code>${p}bd off</code>，再回复起始消息发送 <code>${p}bd</code> — 清理区间内自己的消息

<b>常见提示：</b>
• “没有删除权限”：检查当前模式、管理员权限和范围内是否存在自己的消息。
• 成功回执会在约 2 秒后删除；参数或权限提示也会短暂显示。

<code>${p}bd help</code> / <code>${p}help bulk_delete</code> 查看本说明。`;
}
